import { expect, type Page } from "@playwright/test";

function requiredGeneratedValue(name: string) {
  const value = process.env[name];
  if (!value)
    throw new Error(`${name} must be generated by the Playwright configuration.`);
  return value;
}

/**
 * Sign in through the real UI, tolerating a transient connection reset while
 * the development server is compiling a route. A bounded retry keeps genuine
 * credential or authorization failures visible to the test.
 */
export async function signIn(page: Page, email: string) {
  let lastError: unknown;
  for (let attempt = 0; attempt < 3; attempt += 1) {
    try {
      await page.goto("/login");
      await page.getByLabel("Email address").fill(email);
      await page.getByLabel("Password", { exact: true }).fill(e2ePassword());
      await page.getByRole("button", { name: "Sign in", exact: true }).click();
      await expect(page).toHaveURL(/\/dashboard$/, { timeout: 15_000 });
      return;
    } catch (error) {
      lastError = error;
      if (attempt === 2) throw error;
      await page.waitForTimeout(500);
    }
  }
  throw lastError;
}

function testEmail(label: string) {
  return `${label}-${requiredGeneratedValue("PERMORA_E2E_RUN_ID")}@example.invalid`;
}

export function e2ePassword() {
  return requiredGeneratedValue("PERMORA_E2E_PASSWORD");
}

export function e2eClientHeaders(lastOctet: number) {
  if (!Number.isInteger(lastOctet) || lastOctet < 1 || lastOctet > 254)
    throw new Error("The E2E client address octet must be between 1 and 254.");
  return { "x-forwarded-for": `192.0.2.${lastOctet}` };
}

